#!/usr/bin/env python3
"""Make the renderer's star table from the Bright Star Catalogue (milestone 6
step 4).

    python3 tools/fetch-stars.py [catalog.gz]

Downloads the Yale Bright Star Catalogue, 5th revised edition (Hoffleit &
Warren 1991, NASA ADC), from the Harvard copy (plain HTTP: its HTTPS
certificate names another host, so the file is checked against a pinned
SHA-256 instead), or reads a copy given on the command line, and writes
libs/render/src/vk/star_catalog.inc: each star's J2000 right ascension and
declination (degrees), visual magnitude and B-V colour, brightest first.
The 14 entries that aren't stars (novae and galaxies kept for the numbering)
have no position and are left out; a star without a B-V takes 0.6, about the
sun's.

Standard library only. The output is committed: the build doesn't download.
"""

from __future__ import annotations

import gzip
import hashlib
import pathlib
import sys
import urllib.request

URL = "http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz"
SHA256 = "0471ced07fc241e625613baa689b2fa5f4b59fd733f731003e57d2d436036cdb"
OUT = pathlib.Path(__file__).resolve().parent.parent / "libs/render/src/vk/star_catalog.inc"


def field(line: str, first: int, last: int) -> str:
    """Bytes first to last (1-based, inclusive), as the catalogue's ReadMe."""
    return line[first - 1 : last].strip()


def main() -> int:
    if len(sys.argv) > 1:
        data = pathlib.Path(sys.argv[1]).read_bytes()
    else:
        with urllib.request.urlopen(URL, timeout=120) as r:
            data = r.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        print(f"bsc5.dat.gz: SHA-256 {digest}, expected {SHA256}", file=sys.stderr)
        return 1
    stars = []
    for line in gzip.decompress(data).decode("ascii").splitlines():
        line = line.ljust(197)
        if not field(line, 76, 77) or not field(line, 103, 107):
            continue
        ra = (int(field(line, 76, 77)) + int(field(line, 78, 79)) / 60.0
              + float(field(line, 80, 83)) / 3600.0) * 15.0
        dec = (int(field(line, 85, 86)) + int(field(line, 87, 88)) / 60.0
               + int(field(line, 89, 90)) / 3600.0)
        if field(line, 84, 84) == "-":
            dec = -dec
        vmag = float(field(line, 103, 107))
        bv_text = field(line, 110, 114)
        bv = float(bv_text) if bv_text else 0.6
        stars.append((vmag, ra, dec, bv))
    stars.sort()
    with OUT.open("w", newline="\n") as f:
        f.write("// Generated by tools/fetch-stars.py from the Yale Bright Star Catalogue,\n")
        f.write("// 5th revised edition (Hoffleit & Warren 1991, NASA ADC). Do not edit.\n")
        f.write("// {right ascension, declination (J2000, degrees), V magnitude, B-V},\n")
        f.write(f"// brightest first; {len(stars)} stars.\n")
        f.write("// NOLINTBEGIN(modernize-use-std-numbers): data, some near pi's multiples\n")
        for vmag, ra, dec, bv in stars:
            f.write(f"{{{ra:.5f}F, {dec:.5f}F, {vmag:.2f}F, {bv:.2f}F}},\n")
        f.write("// NOLINTEND(modernize-use-std-numbers)\n")
    print(f"wrote {len(stars)} stars to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
